def export_extraction_json(data: str, doc_title: str) -> str:
    try:
        parsed = json.loads(data)
        return json.dumps({
            "document": doc_title,
            "exported_at": datetime.utcnow().isoformat(),
            "extracted_data": parsed,
        }, indent=2)
    except Exception:
        return json.dumps({
            "document": doc_title,
            "exported_at": datetime.utcnow().isoformat(),
            "extracted_data": data,
        }, indent=2)


def export_extraction_csv(data: str) -> str:
    try:
        parsed = json.loads(data)
        if not isinstance(parsed, dict):
            return data

        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(["Field", "Value"])
        for k, v in parsed.items():
            writer.writerow([k, str(v) if v is not None else ""])
        return output.getvalue()
    except Exception:
        return data
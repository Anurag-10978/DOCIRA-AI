import json
import csv
import io
from datetime import datetime
from sqlalchemy.orm import Session

from app.models.conversation import Conversation, Message
from app.models.knowledge_base import KnowledgeBase


def export_chat_markdown(db: Session, conv_id: int, user_id: int) -> str:
    conv = db.query(Conversation).filter(
        Conversation.id == conv_id,
        Conversation.user_id == user_id,
    ).first()
    if not conv:
        return ""

    lines = [
        f"# {conv.title}",
        f"**Knowledge Base:** KB-{conv.knowledge_base_id}",
        f"**Exported:** {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}",
        "",
        "---",
        "",
    ]

    for msg in conv.messages:
        role_label = "**You**" if msg.role == "user" else "**DOCIRA-AI**"
        lines.append(f"### {role_label}")
        lines.append(msg.content)
        lines.append("")

        if msg.role == "assistant" and msg.citations:
            lines.append("**Sources:**")
            for c in msg.citations:
                lines.append(f"- {c['document_title']} (Page {c['page']}) — {round(c['similarity_score'] * 100)}% match")
            lines.append("")

        if msg.role == "assistant" and msg.ai_metadata:
            m = msg.ai_metadata
            lines.append(f"*{m.get('task_type','').upper()} · {m.get('model','')} · {m.get('latency_ms',0)}ms · {m.get('tokens_used',0)} tokens*")
            lines.append("")

        lines.append("---")
        lines.append("")

    return "\n".join(lines)


def export_chat_txt(db: Session, conv_id: int, user_id: int) -> str:
    conv = db.query(Conversation).filter(
        Conversation.id == conv_id,
        Conversation.user_id == user_id,
    ).first()
    if not conv:
        return ""

    lines = [
        f"CONVERSATION: {conv.title}",
        f"Exported: {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}",
        "=" * 60,
        "",
    ]

    for msg in conv.messages:
        role = "YOU" if msg.role == "user" else "DOCIRA-AI"
        ts = msg.created_at.strftime("%H:%M")
        lines.append(f"[{ts}] {role}:")
        lines.append(msg.content)
        lines.append("")

    return "\n".join(lines)


